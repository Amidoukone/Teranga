const { test, expect } = require('@playwright/test');
const { API_BASE_URL, blockExternalTracking, loginAsSeededClient, seedAuthenticatedSession } = require('./support/realApi');

test('real client creates project and order from the shared list and returns to the same filters', async ({ page, request }, testInfo) => {
  const client = await loginAsSeededClient(request);
  const suffix = String(Date.now());
  await page.setViewportSize({ width: 360, height: 900 });
  await blockExternalTracking(page); await seedAuthenticatedSession(page, client.user, client.token);
  await page.goto('/demandes?type=project');
  const main = page.getByRole('main');
  await main.getByRole('link', { name: 'Nouveau projet', exact: true }).click();
  const projectForm = main.getByRole('form', { name: 'Nouveau projet', exact: true });
  await projectForm.getByLabel('Titre', { exact: true }).fill(`Projet unifié ${suffix}`);
  await projectForm.getByRole('button', { name: 'Créer le projet', exact: true }).click();
  await expect(page).toHaveURL(/\/projects\/\d+$/);
  await main.getByRole('link', { name: 'Retour aux demandes', exact: true }).click();
  expect(new URL(page.url()).searchParams.get('type')).toBe('project');
  await expect(main.getByRole('article', { name: `Projet unifié ${suffix}`, exact: true })).toBeVisible();
  await main.getByRole('combobox').selectOption('order');
  await main.getByRole('link', { name: 'Nouvelle commande', exact: true }).click();
  const orderForm = main.getByRole('form', { name: 'Nouvelle commande', exact: true });
  await orderForm.getByLabel('Note client (optionnel)', { exact: true }).fill(`Commande unifiée ${suffix}`);
  const creating = page.waitForResponse(response => response.url().endsWith('/orders') && response.request().method() === 'POST');
  await orderForm.getByRole('button', { name: 'Créer la commande', exact: true }).click();
  const created = await creating; expect(created.status(), await created.text()).toBe(201);
  const body = await created.json(), order = body.order || body;
  await expect(page).toHaveURL(/\/orders\/\d+$/);
  await main.getByRole('link', { name: 'Montants et paiements', exact: true }).click();
  await main.getByRole('link', { name: 'Retour aux demandes', exact: true }).click();
  expect(new URL(page.url()).searchParams.get('type')).toBe('order');
  await main.getByRole('textbox', { name: 'Rechercher une demande', exact: true }).fill(suffix);
  await main.getByRole('button', { name: 'Rechercher', exact: true }).click();
  await expect(main.getByRole('article')).toHaveCount(1);
  await expect(main.getByRole('article').getByText(`Commande unifiée ${suffix}`, { exact: true })).toBeVisible();
  await expect(main.getByRole('article').getByRole('link', { name: 'Suivre ma demande', exact: true })).toHaveAttribute('href', `/orders/${order.id}`);
  const result = await request.get(`${API_BASE_URL}/v1/requests?view=all&q=${suffix}`, { headers: { Authorization: `Bearer ${client.token}` } });
  expect(result.status(), await result.text()).toBe(200);
  const collection = await result.json(); expect(collection.pagination.total).toBe(2);
  expect(new Set(collection.items.map(item => item.kind))).toEqual(new Set(['project', 'order']));
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false);
  await page.screenshot({ path: testInfo.outputPath('unified-requests-real.png'), fullPage: true });
});
